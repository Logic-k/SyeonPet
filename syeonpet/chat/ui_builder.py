"""UI construction and tab ordering for PromptConversation."""
from __future__ import annotations

from PySide6.QtCore import Qt
from PySide6.QtWidgets import (
    QComboBox, QFormLayout, QHBoxLayout, QLabel, QMenu,
    QPushButton, QTextEdit, QToolButton, QVBoxLayout, QWidget,
)

from optimizer_core import TASKS
from syeonpet.chat.dialogs import CHAT_STYLE, _ActionRow, _StatusText


def setup_chat_ui(widget) -> None:
    widget.setObjectName("promptConversation")
    widget.setAttribute(Qt.WidgetAttribute.WA_StyledBackground, True)
    widget.setStyleSheet(CHAT_STYLE)

    widget.conversation = QTextEdit()
    widget.conversation.setReadOnly(True)
    widget.conversation.setTabChangesFocus(True)
    widget.conversation.setMinimumHeight(50)
    widget.conversation.setAccessibleName("션과 나눈 프롬프트 대화")
    widget.conversation.setPlainText("션: 어떤 요청을 정리할까요?\n처음에는 원하는 일을 적고, 이후에는 추가 조건을 말씀해 주세요.")

    widget.provider = QComboBox()
    widget.provider.setAccessibleName("정리 방식")
    for text, key in (("기본 정리 (AI 사용 안 함)", "offline"),
                      ("AI 정리 · Vireonix", "vireonix"),
                      ("AI 정리 · Pollinations Classic (예비)", "pollinations-classic"),
                      ("AI 정리 · JarvisClaw (무료)", "jarvisclaw"),
                      ("AI 정리 · Kilo (무료)", "kilo"),
                      ("AI 정리 · OVHcloud (무료)", "ovhcloud")):
        widget.provider.addItem(text, key)
    widget.provider.setCurrentIndex(widget.provider.findData("jarvisclaw"))

    widget.provider_note = QLabel()
    widget.provider_note.setObjectName("providerNote")
    widget.provider_note.setWordWrap(True)

    widget.task = QComboBox()
    widget.task.setAccessibleName("작업 유형")
    for key, label in TASKS.items():
        widget.task.addItem(label or "자동", key)
    widget.detail = QComboBox()
    widget.detail.setAccessibleName("상세 수준")
    for key, label in (("concise", "간결하게"), ("balanced", "적절하게"), ("detailed", "상세하게")):
        widget.detail.addItem(label, key)
    widget.detail.setCurrentIndex(1)

    widget.input = QTextEdit()
    widget.input.setObjectName("requestInput")
    widget.input.setAccessibleName("요청 또는 추가 조건")
    widget.input.setToolTip("Enter: 줄바꿈 · Ctrl+Enter: 보내기")
    widget.input.setTabChangesFocus(True)
    widget.input.installEventFilter(widget)
    widget._update_input_example()
    widget.input.setMinimumHeight(65)
    widget.input.setMaximumHeight(110)
    widget.inline_notice = QLabel()
    widget.inline_notice.setObjectName("inlineNotice")
    widget.inline_notice.setAccessibleName("요청 오류 안내")
    widget.inline_notice.setTextFormat(Qt.TextFormat.PlainText)
    widget.inline_notice.setWordWrap(True)
    widget.inline_notice.hide()
    widget.input.textChanged.connect(widget.inline_notice.hide)

    widget.send = QPushButton("션에게 보내기")
    widget.send.setObjectName("primaryAction")
    widget.send.clicked.connect(widget.submit)
    widget._other_ai_target = None
    widget.retry_other = QPushButton()
    widget.retry_other.setAccessibleName("다른 AI 서비스로 다시 보내기")
    widget.retry_other.setToolTip("입력은 그대로 두고 다른 AI 서비스를 선택해 보냅니다. 보내기 전에 전송을 다시 확인합니다.")
    widget.retry_other.clicked.connect(widget._send_to_other_ai)
    widget.retry_other.hide()

    widget.reload_profiles()
    widget.provider.currentIndexChanged.connect(widget._provider_changed)
    widget._provider_changed()

    widget.template = QPushButton("템플릿")
    widget.template.setToolTip("교육지원청 업무와 일반 용도의 예시를 검색해 입력란에 넣습니다.")
    widget.template.clicked.connect(widget._insert_template)
    widget.reset = QPushButton("새 요청")
    widget.reset.clicked.connect(widget._new_request)
    widget.library = QPushButton("보관함")
    widget.library.clicked.connect(widget._open_library)
    widget.flow = QPushButton("단계별 완성형")
    widget.flow.setAccessibleName("진단·되묻기로 완성형 프롬프트 만들기")
    widget.flow.setToolTip("입력만으로 빠진 조건을 진단하고, 한 번에 답을 받아 완성형 프롬프트를 만듭니다. 이 기기에서 처리해요.")
    widget.flow.clicked.connect(widget._open_flow)
    widget._flow_dialog = None
    widget.ai_settings = QPushButton("AI 설정")
    widget.ai_settings.setAccessibleName("AI 설정 열기")
    widget.ai_settings.clicked.connect(widget._open_ai_settings)
    widget.clarify = QPushButton("조건 확인")
    widget.clarify.setAccessibleName("빠진 조건 확인")
    widget.clarify.clicked.connect(widget._open_clarification)
    widget.compare = QPushButton("두 모델 비교")
    widget.compare.setAccessibleName("두 모델 비교")
    widget.compare.clicked.connect(widget._open_comparison)
    widget.diff = QPushButton("원문 차이")
    widget.diff.setAccessibleName("원문과 결과 문자 차이")
    widget.diff.clicked.connect(widget._open_diff)
    widget.tools_toggle = QToolButton()
    widget.tools_toggle.setCheckable(True)
    widget.tools_toggle.setText("도구 더보기")
    widget.tools_toggle.setAccessibleName("추가 도구 표시")
    widget.tools_toggle.setToolTip("조건 확인, 두 모델 비교, 원문 차이를 표시합니다.")
    widget.tools_toggle.toggled.connect(widget._toggle_tools)
    for tool in (widget.clarify, widget.compare, widget.diff):
        tool.hide()

    widget.result_choice = QComboBox()
    widget.result_choice.setAccessibleName("이전 정리 결과 선택")
    widget.result_choice.currentIndexChanged.connect(widget._select_result)
    widget.result = QTextEdit()
    widget.result.setTabChangesFocus(True)
    widget.result.setMinimumHeight(60)
    widget.result.setAccessibleName("정리한 프롬프트 편집")
    widget.copy = QPushButton("결과 복사")
    widget.copy.clicked.connect(widget._copy_result)
    widget.result.textChanged.connect(widget._reset_copy)
    widget.result_choice.activated.connect(widget._reset_copy)
    widget.status = _StatusText("요청을 입력하고 정리 방식을 확인해 주세요.")
    widget.status.setObjectName("statusText")
    widget.result_metadata = QLabel()
    widget.result_metadata.setAccessibleName("선택 결과 모델 정보")
    widget.result_metadata.setWordWrap(True)

    widget._fill_names, widget._fill_fields = (), {}
    widget.fill_toggle = QToolButton()
    widget.fill_toggle.setCheckable(True)
    widget.fill_toggle.setAccessibleName("빈칸 채우기 표시")
    widget.fill_toggle.toggled.connect(widget._toggle_fill)
    widget.fill_toggle.hide()
    widget.fill_panel = QWidget()
    widget.fill_panel.setObjectName("fillPanel")
    widget.fill_panel.setAttribute(Qt.WidgetAttribute.WA_StyledBackground, True)
    fill_layout = QVBoxLayout(widget.fill_panel)
    fill_layout.setContentsMargins(6, 4, 6, 4)
    fill_layout.setSpacing(3)
    widget.fill_form = QFormLayout()
    widget.fill_form.setSpacing(3)
    fill_layout.addLayout(widget.fill_form)
    widget.fill_hint = QLabel()
    widget.fill_hint.setWordWrap(True)
    widget.fill_hint.hide()
    fill_layout.addWidget(widget.fill_hint)
    fill_buttons = _ActionRow()
    fill_buttons.addStretch()
    widget.fill_apply = QPushButton("채운 내용 넣기")
    widget.fill_apply.clicked.connect(widget._apply_fill)
    fill_buttons.addWidget(widget.fill_apply)
    fill_layout.addLayout(fill_buttons)
    widget.fill_panel.hide()
    widget.result.textChanged.connect(widget._refresh_fill)
    widget.result.textChanged.connect(widget._refresh_quality)

    layout = QVBoxLayout(widget)
    layout.setContentsMargins(6, 4, 6, 4)
    layout.setSpacing(3)
    widget.conversation_label = QLabel("션과 프롬프트 정리")
    widget.conversation_label.setObjectName("sectionTitle")
    widget.conversation_label.setBuddy(widget.conversation)
    widget.history_toggle = QToolButton()
    widget.history_toggle.setText("대화 기록 보기")
    widget.history_toggle.setCheckable(True)
    widget.history_toggle.setAccessibleName("대화 기록 표시")
    widget.history_toggle.toggled.connect(widget._toggle_history)
    widget.conversation.hide()

    history_row = _ActionRow()
    history_row.addWidget(widget.conversation_label)
    history_row.addStretch()
    history_row.addWidget(widget.history_toggle)
    layout.addLayout(history_row)
    layout.addWidget(widget.conversation, 1)

    prov_row = _ActionRow()
    prov_lbl = QLabel("정리 방식")
    prov_lbl.setBuddy(widget.provider)
    prov_row.addWidget(prov_lbl)
    prov_row.addWidget(widget.provider, 1)
    prov_row.addWidget(widget.ai_settings)
    layout.addLayout(prov_row)
    layout.addWidget(widget.provider_note)

    task_row = _ActionRow()
    t_lbl = QLabel("작업")
    t_lbl.setBuddy(widget.task)
    task_row.addWidget(t_lbl)
    task_row.addWidget(widget.task, 1)
    d_lbl = QLabel("상세")
    d_lbl.setBuddy(widget.detail)
    task_row.addWidget(d_lbl)
    task_row.addWidget(widget.detail, 1)
    layout.addLayout(task_row)

    in_row = _ActionRow()
    in_lbl = QLabel("1. 요청 · 추가 조건")
    in_lbl.setObjectName("sectionTitle")
    in_lbl.setBuddy(widget.input)
    in_row.addWidget(in_lbl)
    in_row.addStretch()
    in_row.addWidget(widget.template)
    in_row.addWidget(widget.library)
    in_row.addWidget(widget.reset)
    layout.addLayout(in_row)
    layout.addWidget(widget.input)
    layout.addWidget(widget.inline_notice)

    send_row = _ActionRow()
    send_row.addWidget(widget.retry_other)
    send_row.addWidget(widget.tools_toggle)
    send_row.addStretch()
    send_row.addWidget(widget.flow)
    send_row.addWidget(widget.send)
    layout.addLayout(send_row)

    tools_row = _ActionRow()
    tools_row.addWidget(widget.clarify)
    tools_row.addWidget(widget.compare)
    tools_row.addWidget(widget.diff)
    layout.addLayout(tools_row)

    res_row = _ActionRow()
    res_lbl = QLabel("2. 정리 결과")
    res_lbl.setToolTip("정리 결과를 직접 수정할 수 있습니다.")
    res_lbl.setObjectName("sectionTitle")
    res_lbl.setBuddy(widget.result)
    res_row.addWidget(res_lbl)
    res_row.addWidget(widget.result_choice, 1)
    res_row.addWidget(widget.copy)
    layout.addLayout(res_row)
    layout.addWidget(widget.result, 3)
    layout.addWidget(widget.fill_toggle, 0, Qt.AlignmentFlag.AlignLeft)
    layout.addWidget(widget.fill_panel)
    layout.addWidget(widget.result_metadata)
    layout.addWidget(widget.status)

    widget.ensurePolished()
    copy_w = widget.copy.sizeHint().width()
    widget.copy.setText("복사됨")
    widget.copy.setFixedWidth(max(copy_w, widget.copy.sizeHint().width()))
    widget._reset_copy()
    controls = (widget.history_toggle, widget.provider, widget.ai_settings, widget.task, widget.detail,
                widget.template, widget.library, widget.reset, widget.input, widget.send, widget.flow,
                widget.retry_other, widget.tools_toggle, widget.clarify, widget.compare, widget.diff,
                widget.result_choice, widget.copy, widget.result,
                widget.fill_toggle, widget.status)
    for before, after in zip(controls, controls[1:]):
        QWidget.setTabOrder(before, after)
